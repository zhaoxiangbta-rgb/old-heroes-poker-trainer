import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_ROOT = fileURLToPath(new URL("..", import.meta.url));
const IDS = Array.from({ length: 6 }, (_, index) => `friend-0${index + 1}`);

function validateNames(input) {
  if (!input || typeof input !== "object" || Array.isArray(input))
    throw new Error("local player names must be a JSON object");
  const keys = Object.keys(input).sort();
  if (keys.length !== IDS.length || keys.some((key, index) => key !== IDS[index]))
    throw new Error("local player names must contain exactly friend-01 through friend-06");
  const names = {};
  for (const id of IDS) {
    if (typeof input[id] !== "string") throw new Error(`${id} must be a string`);
    const name = input[id].trim();
    if (!name) throw new Error(`${id} must not be blank`);
    if (name === "你") throw new Error(`${id} uses a reserved name`);
    if (Array.from(name).length > 12)
      throw new Error(`${id} must contain at most 12 Unicode characters`);
    names[id] = name;
  }
  if (new Set(Object.values(names)).size !== IDS.length)
    throw new Error("local player names must be unique");
  return names;
}

export async function prepareNames({ mode, inputPath, outputPath, quiet = false }) {
  if (mode !== "public" && mode !== "private")
    throw new Error("player name mode must be public or private");
  let names = {};
  if (mode === "private") {
    if (!existsSync(inputPath)) throw new Error("private player name configuration is missing");
    names = validateNames(JSON.parse(readFileSync(inputPath, "utf8")));
  }
  mkdirSync(dirname(outputPath), { recursive: true });
  const source = [
    "// Generated by scripts/prepare-player-names.mjs. Do not commit.",
    `export const BUILD_PLAYER_NAME_OVERRIDES = Object.freeze(${JSON.stringify(names, null, 2)}) as Readonly<Partial<Record<string, string>>>;`,
    "",
  ].join("\n");
  writeFileSync(outputPath, source, "utf8");
  if (!quiet)
    console.log(mode === "private" ? "loaded six local player names" : "using public player names");
}

function cliMode() {
  const argument = process.argv.find((item) => item.startsWith("--mode="));
  const requested = argument?.slice("--mode=".length) ?? process.env.PLAYER_NAMES_MODE;
  return requested === "private" ? "private" : "public";
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await prepareNames({
    mode: cliMode(),
    inputPath: resolve(PROJECT_ROOT, "config/player-names.local.json"),
    outputPath: resolve(PROJECT_ROOT, "src/config/playerNames.generated.ts"),
  });
}
